function getContent(slug: string, name: string) {
  const custom = SERVICE_CONTENT[slug];
  if (custom) return custom;
  return {
    intro: `${name} — це важливий вид навчальної роботи, який вимагає часу, знань та уважності до деталей. Правильний підхід до структури, оформлення та змісту гарантує високу оцінку.`,
    sections: [
      { title: 'На що звернути увагу', text: `При написанні ${name.toLowerCase()} важливо дотримуватись вимог вашого ВНЗ: оформлення за стандартами, актуальні джерела, логічна структура та обґрунтовані висновки.` },
    ],
  };
}

export async function generateStaticParams() {
  const workTypes = await getWorkTypes().catch(() => []);
  return workTypes.map(wt => ({ slug: wt.slug }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { slug } = await params;
  const workTypes = await getWorkTypes().catch(() => []);
  const wt = workTypes.find(t => t.slug === slug);
  if (!wt) return { title: 'Послуга не знайдена' };
  return {
    title: `${wt.name}: структура, оформлення, поради`,
    description: `Як написати ${wt.name.toLowerCase()}: покрокова інструкція, вимоги до оформлення, типові помилки. Поради від досвідчених авторів.`,
    openGraph: { title: `${wt.name} — поради з написання | Шпаргалочка` },
  };
}

