export interface ParsedTask {
  subject: string;
  subjectName: string;
  workType: string;
  description: string;
}

export function parseTaskText(text: string): ParsedTask {
  const t = text.trim();
  if (!t) return { subject: '', subjectName: '', workType: '', description: '' };

  let workType = '';
  let subjectName = '';

  for (const [re, wt] of WORK_TYPE_RULES) {
    if (re.test(t)) { workType = wt; break; }
  }

  for (const [re, sn] of SUBJECT_RULES) {
    if (re.test(t)) { subjectName = sn; break; }
  }

  return {
    subject: t.slice(0, 110),
    subjectName,
    workType,
    description: t.length > 110 ? t : '',
  };
}
